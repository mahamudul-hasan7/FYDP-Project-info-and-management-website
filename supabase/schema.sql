-- =============================================================================
-- Row Level Security (RLS) Configuration
-- =============================================================================
-- Server-side mutations will be performed via the Supabase Secret Key (Server Client)
-- (which automatically bypasses RLS). Public read policies are strictly read-only.
-- =============================================================================

-- Enable RLS on all tables
ALTER TABLE members ENABLE ROW LEVEL SECURITY;
ALTER TABLE tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE sprint_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE team_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE banner_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE project_info ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_credentials ENABLE ROW LEVEL SECURITY;

-- 1. Public Read Policies
DROP POLICY IF EXISTS "Public can view members" ON members;
CREATE POLICY "Public can view members"
    ON members FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public can view sprint logs" ON sprint_logs;
CREATE POLICY "Public can view sprint logs"
    ON sprint_logs FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public can view banner config" ON banner_config;
CREATE POLICY "Public can view banner config"
    ON banner_config FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Public can view project info" ON project_info;
CREATE POLICY "Public can view project info"
    ON project_info FOR SELECT
    USING (true);

