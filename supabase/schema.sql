-- =============================================================================
-- Team Random FYDP — Production Supabase Schema
-- =============================================================================
-- This schema establishes the relational database structure, indexing,
-- automated update triggers, and Row Level Security (RLS) policies for
-- the Team Random FYDP platform.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Helper Function: Automatic `updated_at` Timestamp Trigger
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ language 'plpgsql';

-- -----------------------------------------------------------------------------
-- 2. Members Table
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS members (
    slug TEXT PRIMARY KEY,
    student_id TEXT,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT DEFAULT 'Not provided',
    gender TEXT,
    department TEXT DEFAULT 'Department of Computer Science & Engineering',
    institution TEXT DEFAULT 'United International University',
    role TEXT NOT NULL,
    short_role TEXT,
    tagline TEXT,
    initials TEXT,
    image TEXT,
    admin_avatar_style TEXT,
    image_position TEXT,
    image_fit TEXT,
    placeholder TEXT,
    github TEXT,
    linkedin TEXT,
    about TEXT,
    responsibilities JSONB DEFAULT '[]'::jsonb,
    skills JSONB DEFAULT '[]'::jsonb,
    focus JSONB DEFAULT '[]'::jsonb,
    custom_links JSONB DEFAULT '[]'::jsonb,
    privacy JSONB DEFAULT '{"email": true, "phone": true, "github": true, "linkedin": true}'::jsonb,
    display_order INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_members_student_id ON members(student_id);
CREATE INDEX IF NOT EXISTS idx_members_email ON members(email);
CREATE INDEX IF NOT EXISTS idx_members_display_order ON members(display_order);

DROP TRIGGER IF EXISTS set_members_updated_at ON members;
CREATE TRIGGER set_members_updated_at
    BEFORE UPDATE ON members
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

-- -----------------------------------------------------------------------------
-- 3. Tasks Table (Directives / Kanban)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT DEFAULT '',
    assignee TEXT NOT NULL,
    assignee_slug TEXT REFERENCES members(slug) ON UPDATE CASCADE ON DELETE SET NULL,
    priority TEXT NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('HIGH', 'MEDIUM', 'LOW')),
    due_date TEXT,
    status TEXT NOT NULL DEFAULT 'TODO' CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    created_by TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_tasks_assignee_slug ON tasks(assignee_slug);
CREATE INDEX IF NOT EXISTS idx_tasks_status ON tasks(status);
CREATE INDEX IF NOT EXISTS idx_tasks_priority ON tasks(priority);
CREATE INDEX IF NOT EXISTS idx_tasks_created_at ON tasks(created_at DESC);

DROP TRIGGER IF EXISTS set_tasks_updated_at ON tasks;
CREATE TRIGGER set_tasks_updated_at
    BEFORE UPDATE ON tasks
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

